# CPU and Memory Calculator

# Problem

# A server has:
# 4 CPUs
# 8 GB RAM

# Print the total resources available.

cpu = 4
memory = 8

print("----- Current Server ------")
print("CPU: ",cpu)
print("Memory: ", memory,"GB")

new_cpu = cpu * 2
new_memory = memory * 2

print("\n----- After Scaling ------")
print("CPU: ", new_cpu)
print("Memory: ", new_memory,"GB")